function ConvertTo-OSDStageDeploymentScript {
    <#
    .SYNOPSIS
    Converts a validated OSDStage deployment profile to deterministic PowerShell.
    .DESCRIPTION
    Generates PowerShell text only. The generated script is not executed.
    #>
    [CmdletBinding(DefaultParameterSetName='Path')]
    param(
        [Parameter(Mandatory, Position=0, ParameterSetName='Path')]
        [string]$Path,

        [Parameter(Mandatory, ValueFromPipeline, ParameterSetName='InputObject')]
        [psobject]$InputObject
    )

    process {
        $profileParameters = @{}
        if ($PSCmdlet.ParameterSetName -eq 'Path') { $profileParameters.Path = $Path }
        else { $profileParameters.InputObject = $InputObject }

        $profile = Read-OSDStageDeploymentProfile @profileParameters
        $validation = Test-OSDStageDeploymentProfileInternal -Profile $profile
        if (-not $validation.Valid) {
            throw "Deployment profile is invalid:$([Environment]::NewLine)$($validation.Errors -join [Environment]::NewLine)"
        }

        $lines = [System.Collections.Generic.List[string]]::new()
        $lines.Add("# Generated by OSDStage from deployment profile '$([string]$profile.Name)'")
        $lines.Add('# Review this script before execution. OSDStage does not execute generated code automatically.')
        $lines.Add('')

        foreach ($package in @($profile.Packages)) {
            $command = Get-OSDStageDeploymentProfileCommand -Package $package
            $parts = [System.Collections.Generic.List[string]]::new()
            $parts.Add($command.Name)

            if ([string]$package.Source -eq 'Repository') {
                $parts.Add("-Name $(ConvertTo-OSDStagePowerShellLiteral -Value ([string]$package.Id))")
            }

            if ($package.PSObject.Properties.Name -contains 'Parameters' -and $null -ne $package.Parameters) {
                foreach ($property in @($package.Parameters.PSObject.Properties | Sort-Object Name)) {
                    $name = [string]$property.Name
                    $value = $property.Value
                    $metadata = $command.Parameters[$name]

                    if ($metadata.ParameterType -eq [System.Management.Automation.SwitchParameter]) {
                        $switchLiteral = if ([bool]$value) { '$true' } else { '$false' }
                        $parts.Add(('-{0}:{1}' -f $name,$switchLiteral))
                    }
                    else {
                        $parts.Add("-$name $(ConvertTo-OSDStagePowerShellLiteral -Value $value)")
                    }
                }
            }

            $lines.Add(($parts -join ' '))
        }

        $lines -join [Environment]::NewLine
    }
}
